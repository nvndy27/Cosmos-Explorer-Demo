#!/usr/bin/env python3
"""Build file://-compatible JS from reviewed local snapshots; no network."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]/'cosmos-explorer'
def load(name):return json.loads((ROOT/'data'/name).read_text())
records=load('messier-snapshot.json')['records']+load('exoplanet-records.json')
# Preserve NASA classification; choose a matching illustrative silhouette.
for r in records:
 if r['level']=='galaxies':
  typ=r['stats'][3][1].lower()
  if any(word in typ for word in ['elliptical','lenticular']):r['type']='elliptical'
  elif 'irregular' in typ:r['type']='irregular'
patches=load('image-patches.json')
output="'use strict';\n// Generated by scripts/build_catalog.py from versioned NASA snapshots.\n"
output+='data.push(...'+json.dumps(records,ensure_ascii=False,indent=2)+');\n'
output+='const imagePatches='+json.dumps(patches,ensure_ascii=False,indent=2)+';\n'
output+="for(const o of data){Object.assign(o,imagePatches[o.id]||{});if(o.id==='trappist')o.level='exoplanets';}\n"
upgrade=load('upgrade22-snapshot.json')
output+='const upgrade22='+json.dumps(upgrade['newRecords'],ensure_ascii=False,indent=2)+';\n'
output+='const metadata22='+json.dumps(upgrade['metadata'],ensure_ascii=False,indent=2)+';\n'
output+='const patches22='+json.dumps(upgrade['patches'],ensure_ascii=False,indent=2)+';\n'
output+="for(const o of data){Object.assign(o,metadata22[o.id]||{},patches22[o.id]||{});if(o.extraReferences)o.references.push(...o.extraReferences);if(o.classification==='exoplanet')o.level='exoplanets';}\n"
output+="data.push(...upgrade22);\n"
exo_images=load('exoplanet-image-snapshot.json')['patches']
output+='const exoplanetImages22='+json.dumps(exo_images,ensure_ascii=False,indent=2)+';\n'
output+="for(const o of data)Object.assign(o,exoplanetImages22[o.id]||{});\n"
# Translate legacy display classifications and English boilerplate; original citations remain intact.
output+="const displayTypes22={ 'Globular Cluster':'Cụm sao cầu','Open Cluster':'Cụm sao mở','Star Cloud':'Đám mây sao','Spiral Galaxy':'Thiên hà xoắn ốc','Elliptical Galaxy':'Thiên hà elip','Compact Elliptical Galaxy':'Thiên hà elip nhỏ gọn','Barred Spiral Galaxy':'Thiên hà xoắn ốc có thanh','Lenticular Galaxy':'Thiên hà thấu kính','Planetary Nebula':'Tinh vân hành tinh','Emission Nebula':'Tinh vân phát xạ','Reflection Nebula':'Tinh vân phản xạ','Galaxy':'Thiên hà','Nebula':'Tinh vân'};\n"
output+="for(const o of data){o.stats=o.stats.map(([a,b])=>[a,displayTypes22[b]||b]);if(o.id.startsWith('messier-')){o.research='Các quan sát Hubble giúp nghiên cứu '+o.small.toLocaleLowerCase('vi')+' này. Khoảng cách và độ sáng được dẫn từ hồ sơ NASA; xem nguồn để hiểu phương pháp và vùng quan sát.';o.fact='Ký hiệu Messier là tên trong danh mục thiên thể sâu. Cấp sao biểu kiến mô tả độ sáng nhìn từ Trái Đất, không phải kích thước hoặc độ sáng nội tại.';}o.imageKind=o.imageKind||(o.image?(o.type==='blackhole'?'reconstruction':o.id==='earth'?'composite':'observation'):'illustration');}\n"
(ROOT/'catalog-expanded.js').write_text(output)
print('Existing extensions:',len(records),'; new 2.2:',len(upgrade['newRecords']),'; upgraded:',len(upgrade['patches']),'profiles.')
